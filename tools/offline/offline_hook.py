"""Offline support for the khgeo books.

Every build writes ``offline-manifest.json`` (list of files the "save for offline"
button stores in the browser through ``sw.js``).

With OFFLINE_BUILD=1 (used by tools/offline/build_offline.py) the built site is also
made to work from a plain folder opened by double-click (file://):
* every data file under assets/data is wrapped in a small JS chunk, and
  assets/js/offline-fetch.js answers fetch() calls from those chunks;
* that script is inserted first in every page and slide;
* links to folders ("slides/") get "index.html" appended.
"""
from pathlib import Path
import base64, hashlib, json, os, re

SKIP_EXT = {".pdf", ".zip", ".tif", ".tiff", ".gpkg", ".map"}
DATA_EXT = {".json": "application/json", ".geojson": "application/geo+json", ".csv": "text/csv",
            ".txt": "text/plain", ".png": "image/png", ".jpg": "image/jpeg", ".jpeg": "image/jpeg",
            ".svg": "image/svg+xml", ".webp": "image/webp", ".bin": "application/octet-stream"}

FETCH_JS = r"""/* Offline fetch for file:// — generated by tools/offline/offline_hook.py */
(function () {
  if (location.protocol !== "file:" || window.__offlineFetch) return;
  var me = document.currentScript && document.currentScript.src || "";
  var ROOT = me.replace(/assets\/js\/offline-fetch\.js.*$/, "");
  var INDEX = __INDEX__, got = {}, wait = {};
  window.__offlineFile = function (k, type, b64) {
    var bin = atob(b64), a = new Uint8Array(bin.length);
    for (var i = 0; i < bin.length; i++) a[i] = bin.charCodeAt(i);
    got[k] = new Blob([a], { type: type });
    (wait[k] || []).forEach(function (f) { f(); }); delete wait[k];
  };
  function load(k) {
    return new Promise(function (ok, bad) {
      if (got[k]) return ok(got[k]);
      if (wait[k]) return wait[k].push(function () { ok(got[k]); });
      wait[k] = [function () { ok(got[k]); }];
      var s = document.createElement("script"); s.src = ROOT + "assets/offline/" + INDEX[k] + ".js";
      s.onerror = function () { bad(new TypeError("offline file missing: " + k)); };
      document.head.appendChild(s);
    });
  }
  var orig = window.fetch ? window.fetch.bind(window) : null;
  window.__offlineFetch = window.fetch = function (input, init) {
    var u = typeof input === "string" ? input : input && input.url !== undefined ? input.url : String(input);
    var abs = new URL(u, location.href).href.split("#")[0].split("?")[0];
    var k = abs.indexOf(ROOT) === 0 ? decodeURIComponent(abs.slice(ROOT.length)) : null;
    if (!k || !Object.prototype.hasOwnProperty.call(INDEX, k)) {
      // paths written for folder URLs (lessons/x/) climb one level too far in file mode
      var i = abs.lastIndexOf("/assets/data/"); k = i < 0 ? null : decodeURIComponent(abs.slice(i + 1));
    }
    if (k && Object.prototype.hasOwnProperty.call(INDEX, k))
      return load(k).then(function (b) { return new Response(b, { status: 200, headers: { "Content-Type": b.type } }); });
    if (!orig) return Promise.reject(new TypeError("fetch unavailable"));
    return orig(input, init);
  };
})();
"""

def on_config(config):
    snippets = config.mdx_configs.setdefault("pymdownx.snippets", {})
    snippets.setdefault("base_path", [config.docs_dir])
    return config

def _rel(site, path):
    return path.relative_to(site).as_posix()

def on_post_build(config):
    site = Path(config.site_dir)
    offline = os.environ.get("OFFLINE_BUILD") == "1"
    if offline:
        _make_file_mode(site)
    # manifest for the service worker ("save the whole book")
    files, h = [], hashlib.sha1()
    for p in sorted(site.rglob("*")):
        if not p.is_file() or p.suffix.lower() in SKIP_EXT: continue
        r = _rel(site, p)
        if r in ("sw.js", "offline-manifest.json") or r.startswith(("downloads/", "assets/offline/")): continue
        if r == "404.html": continue
        b = p.read_bytes(); h.update(r.encode()); h.update(hashlib.sha1(b).digest())
        files.append([r, len(b)])
        if r.endswith("index.html"):
            files.append([r[: -len("index.html")], 0])  # directory URL of the same page
    (site / "offline-manifest.json").write_text(json.dumps(
        {"version": h.hexdigest()[:12], "bytes": sum(s for _, s in files), "files": files},
        ensure_ascii=False, separators=(",", ":")), encoding="utf-8")

def _make_file_mode(site):
    data = site / "assets" / "data"
    out = site / "assets" / "offline"; out.mkdir(parents=True, exist_ok=True)
    index = {}
    for n, p in enumerate(sorted(x for x in data.rglob("*") if x.is_file() and x.suffix.lower() in DATA_EXT)):
        k = _rel(site, p)
        b64 = base64.b64encode(p.read_bytes()).decode()
        (out / f"f{n}.js").write_text(f'__offlineFile({json.dumps(k)},"{DATA_EXT[p.suffix.lower()]}","{b64}");', encoding="utf-8")
        index[k] = f"f{n}"
    js = site / "assets" / "js"; js.mkdir(parents=True, exist_ok=True)
    (js / "offline-fetch.js").write_text(FETCH_JS.replace("__INDEX__", json.dumps(index, ensure_ascii=False)), encoding="utf-8")
    dir_link = re.compile(r'(href=")((?![a-z]+:|#|/)[^"#?]*/)(["#?])')
    for page in site.rglob("*.html"):
        s = page.read_text(encoding="utf-8")
        depth = len(page.relative_to(site).parts) - 1
        tag = f'<script src="{"../" * depth}assets/js/offline-fetch.js"></script>'
        if "offline-fetch.js" not in s:
            s = re.sub(r"<head([^>]*)>", lambda m: m.group(0) + tag, s, count=1)
        s = dir_link.sub(lambda m: m.group(1) + m.group(2) + "index.html" + m.group(3), s)
        s = s.replace('href=""', 'href="index.html"').replace('href="."', 'href="index.html"').replace('href="./"', 'href="./index.html"')
        page.write_text(s, encoding="utf-8")
